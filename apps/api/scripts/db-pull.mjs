// Regenerates src/db/schema.ts from the database (`npm run db:pull`).
//
// Drizzle is only the API's query layer: migrations stay as Supabase SQL in
// supabase/migrations. This wraps `drizzle-kit pull` and fixes what it gets
// wrong for us, so the result is safe to run against production:
//
// 1. Local-only objects from the unmerged UAE bank-sync work (bank_* tables
//    are excluded by drizzle.config.ts; transactions.bank_account_id and its
//    index/FK are stripped here). If they stayed, a plain select() on
//    transactions would name a column production doesn't have.
// 2. Some defaults come out as invalid TypeScript: ones that call SQL
//    functions (e.g. `.default(encode(gen_random_bytes(16), \'hex\'::text))`)
//    are rewritten as sql`` template defaults, and empty strings ('') that
//    come out as `.default(')` are repaired.
//    Foreign-key blocks and tsvector columns are dropped too (see below).
// 3. The generated migration file, snapshot and relations are deleted — we
//    never run drizzle-kit migrations, and queries spell out their joins.
//
// Before relying on a fresh pull, diff local vs production columns (see
// SESSION.md "Local DB Drift"): local can drift from prod.
import { execFileSync } from "node:child_process"
import { existsSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs"

const OUT = "src/db/introspected"
const TARGET = "src/db/schema.ts"
const LOCAL_ONLY_COLUMNS = ["bankAccountId"]

rmSync(OUT, { recursive: true, force: true })
execFileSync("npx", ["drizzle-kit", "pull"], { stdio: ["ignore", "ignore", "inherit"] })

let schema = readFileSync(`${OUT}/schema.ts`, "utf8")

// (2) function-call defaults → sql`...`
schema = schema
  .split("\n")
  .map((line) => {
    const start = line.indexOf(".default(")
    if (start === -1) return line
    // Function calls: escaped quotes inside, or a bare call like gen_x().
    const after = line.slice(start + ".default(".length)
    if (!line.includes("\\'") && !/^[a-z_][a-z0-9_]*\(/.test(after)) return line
    let depth = 0
    let end = -1
    for (let i = start + ".default".length; i < line.length; i++) {
      if (line[i] === "(") depth++
      else if (line[i] === ")" && --depth === 0) {
        end = i
        break
      }
    }
    if (end === -1) throw new Error(`Unbalanced default: ${line}`)
    const expr = line.slice(start + ".default(".length, end).replaceAll("\\'", "'")
    return `${line.slice(0, start)}.default(sql\`${expr}\`)${line.slice(end + 1)}`
  })
  .join("\n")

// (2b) empty-string defaults ('') come out as `.default(')`
schema = schema.replaceAll(".default(')", ".default('')")

// (2c) Foreign keys are only migration metadata for Drizzle, and we never run
// Drizzle migrations; two tables reference each other (invoice_payments ↔
// transactions), which TypeScript can't type. Drop every foreignKey block.
schema = schema.replace(/\n\s*foreignKey\(\{[\s\S]*?\}\)(\.on(Update|Delete)\("[^"]*"\))*,?/g, "")

// (2d) Types drizzle-kit doesn't know (tsvector search columns) come out as
// `unknown("…")`. They're database-generated and never written; drop them.
const unknownColumns = [...schema.matchAll(/^\s*(\w+): unknown\(/gm)].map((m) => m[1])
schema = schema
  .split("\n")
  .filter((line) => !/^\s*\w+: unknown\(/.test(line))
  // …and any index built on one of them.
  .filter((line) => !(line.includes("index(") && unknownColumns.some((c) => line.includes(`table.${c}`))))
  .join("\n")

// (1) local-only columns, plus any index/foreign key that uses them
for (const column of LOCAL_ONLY_COLUMNS) {
  schema = schema
    .split("\n")
    .filter((line) => !line.includes(`${column}:`) && !(line.includes("index(") && line.includes(`table.${column}`)))
    .join("\n")
  schema = schema.replace(new RegExp(`\\n\\s*foreignKey\\(\\{[^}]*table\\.${column}[^}]*\\}\\)[^,\\n]*,?`, "g"), "")
}
// Enums that only the excluded bank tables used.
schema = schema.replace(/^export const bank\w+ = pgEnum\(.*\n/gm, "")

if (/bank_accounts|bank_connections|bank_provider|bankAccount|bankConnection/i.test(schema)) throw new Error("Local-only bank-sync objects are still in the schema")

const header = `// GENERATED by scripts/db-pull.mjs from the database schema — don't edit by hand.
// Regenerate with \`npm run db:pull --workspace=@travada-books/api\`.
// Migrations live in supabase/migrations; this file is only for typed queries.
`
writeFileSync(`${OUT}/schema.ts`, header + schema)
renameSync(`${OUT}/schema.ts`, TARGET)
rmSync(OUT, { recursive: true, force: true })
if (!existsSync(TARGET)) throw new Error("schema.ts was not written")
console.log(`Wrote ${TARGET}`)
