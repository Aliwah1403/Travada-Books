function BrandSvg({ path, hex, size = 16 }: { path: string; hex: string; size?: IconProps["size"] }) {
  return (
    <svg role="img" viewBox="0 0 24 24" width={size} height={size} fill={`#${hex}`}>
      <path d={path} />
    </svg>
  )
}

function fromSimpleIcon(icon: SimpleIcon) {
  return function BrandIcon({ size }: IconProps) {
    return <BrandSvg path={icon.path} hex={icon.hex} size={size} />
  }
}

